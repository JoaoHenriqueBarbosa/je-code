fn lines(parts: &[&str]) -> String {
    parts.join("\n")
}

fn darwin_system_info() -> SystemInfo {
    SystemInfo {
        machine_info: MachineInfo {
            os: "Darwin".to_string(),
            cpus: Some("Intel(R) Core(TM) i7-7700HQ CPU @ 2.80GHz (8 x 2800)".to_string()),
            memory: "16.00GB".to_string(),
            vm_hint: "0%".to_string(),
            linux_env: None,
        },
        process_args: String::new(),
        gpu_status: Vec::new(),
        screen_reader: "no".to_string(),
        remote_data: Vec::new(),
        load: None,
    }
}

fn gpu_status() -> Vec<(String, String)> {
    vec![
        ("2d_canvas".to_string(), "enabled".to_string()),
        ("checker_imaging".to_string(), "disabled_off".to_string()),
    ]
}

fn model_with(data: IssueReporterData) -> std::rc::Rc<IssueReporterModel> {
    IssueReporterModel::new(Some(data))
}

#[test]
fn sets_defaults_to_include_all_data() {
    let guard = ensure_no_disposables_are_leaked_in_test_suite();
    let issue_reporter_model = guard.add_rc(IssueReporterModel::new(None));
    assert_eq!(
        *issue_reporter_model.get_data(),
        IssueReporterData {
            all_extensions: Vec::new(),
            include_system_info: true,
            include_extension_data: true,
            include_workspace_info: true,
            include_process_info: true,
            include_extensions: true,
            include_experiments: true,
            issue_type: IssueType::Bug,
            ..IssueReporterData::default()
        }
    );
    assert_eq!(issue_reporter_model.get_data().issue_type as u8, 0);
}

