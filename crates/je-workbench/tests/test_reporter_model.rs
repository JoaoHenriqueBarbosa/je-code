//! caso a caso e na mesma ordem.
//!
//! Notas de tradução:
//! - `const store = ensureNoDisposablesAreLeakedInTestSuite()` e `store.add(new IssueReporterModel(...))` viram o
//!   guarda criado no começo de cada caso e `guard.add_rc(IssueReporterModel::new(...))`.
//! - `new IssueReporterModel({ ... })` (um `Partial`) é `IssueReporterModel::new(Some(IssueReporterData { ...,
//!   ..IssueReporterData::default() }))`: os campos que o caso omite ficam nos padrões do original.
//! - O `SystemInfo` que os casos repetem (`os`, `cpus`, `memory`, `vmHint`, `processArgs`, `screenReader`) vem de
//!   `darwin_system_info()`, e cada caso troca só o que o original troca.
//! - Os textos esperados são as linhas do template literal do original, unidas com `\n`.

#[path = "../../je-base/tests/common/mod.rs"]
mod common;

use common::ensure_no_disposables_are_leaked_in_test_suite;
use je_platform::diagnostics::{
    DiagnosticInfo, LinuxEnv, MachineInfo, RemoteDiagnostic, RemoteDiagnosticInfo, SystemInfo,
};
