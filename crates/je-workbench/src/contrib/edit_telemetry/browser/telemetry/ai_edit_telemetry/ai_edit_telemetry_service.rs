use je_editor::code_action::languages::ProviderId;
use je_editor::text_model_edit_source::{EditDeltaInfo, EditSuggestionId};
use je_instantiation::service_id;

/// `IAiEditTelemetryService`.
pub trait IAiEditTelemetryService {
    /// `createSuggestionId(data)`.
    fn create_suggestion_id(&self, data: &EditTelemetryCodeSuggestedData) -> EditSuggestionId;

    fn handle_code_accepted(&self, data: &EditTelemetryCodeAcceptedData);

    fn handle_code_rejected(&self, data: &EditTelemetryCodeRejectedData);
}

service_id!(pub I_AI_EDIT_TELEMETRY_SERVICE: dyn IAiEditTelemetryService = "aiEditTelemetryService");

/// `feature`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EditTelemetryFeature {
    /// Code suggestions generated in the sidebar chat panel.
    SideBarChat,
    /// Code suggestions generated through inline chat within the editor.
    InlineChat,
    /// Inline code completion suggestions.
    InlineSuggestion,
}

impl EditTelemetryFeature {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::SideBarChat => "sideBarChat",
            Self::InlineChat => "inlineChat",
            Self::InlineSuggestion => "inlineSuggestion",
        }
    }
}

/// `presentation`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EditTelemetryPresentation {
    /// Code displayed in a code block within chat responses. Only possible when feature is `sideBarChat` or `inlineChat`.
    CodeBlock,
    /// Code already applied to the editor and highlighted with diff-style formatting. Only possible when feature is
    /// `sideBarChat` or `inlineChat`.
    HighlightedEdit,
    /// Code suggested inline as completion text. Only possible when feature is `inlineSuggestion`.
    InlineCompletion,
    /// Code shown as next edit suggestion. Only possible when feature is `nextEditSuggestion`.
    NextEditSuggestion,
}

impl EditTelemetryPresentation {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::CodeBlock => "codeBlock",
            Self::HighlightedEdit => "highlightedEdit",
            Self::InlineCompletion => "inlineCompletion",
            Self::NextEditSuggestion => "nextEditSuggestion",
        }
    }
}

/// `IEditTelemetryBaseData`.
#[derive(Clone, Debug)]
pub struct EditTelemetryBaseData {
    pub suggestion_id: Option<EditSuggestionId>,
    pub feature: Option<EditTelemetryFeature>,
    pub presentation: EditTelemetryPresentation,
    pub source: Option<ProviderId>,
    pub language_id: Option<String>,
    pub edit_delta_info: Option<EditDeltaInfo>,
    /// `'ask' | 'edit' | 'agent' | 'custom' | 'applyCodeBlock' | undefined`.
    pub mode_id: Option<String>,
    /// Is set if modeId is applyCodeBlock.
    pub apply_code_block_suggestion_id: Option<EditSuggestionId>,
    /// e.g. 'gpt-4o', 'gpt-4o-mini', 'gpt-3.5-turbo'.
    pub model_id: Option<String>,
    /// Source controlled id. For chat edits and code-block actions this is the originating chat request id.
    pub source_request_id: Option<String>,
    /// Whether the edit was generated by an Agent Host-backed chat session.
    pub is_agent_host_session: Option<bool>,
}

/// `IEditTelemetryCodeSuggestedData`.
#[derive(Clone, Debug)]
pub struct EditTelemetryCodeSuggestedData {
    pub base: EditTelemetryBaseData,
    /// The agent implementation that produced the code block.
    pub provider: Option<String>,
}

/// `acceptanceMethod`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AcceptanceMethod {
    /// Insert code at the current cursor position in the active editor. Only possible when presentation is `codeBlock`.
    InsertAtCursor,
    /// Create a new file and insert the code there. Only possible when presentation is `codeBlock`.
    InsertInNewFile,
    /// User manually copied the code. Only possible when presentation is `codeBlock`.
    CopyManual,
    /// User clicked a copy button to copy the code. Only possible when presentation is `codeBlock`.
    CopyButton,
    /// User accepted the suggestion by clicking 'keep' (when presentation is `highlightedEdit`) or pressing Tab (when
    /// feature is `inlineSuggestion`).
    Accept,
}

impl AcceptanceMethod {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::InsertAtCursor => "insertAtCursor",
            Self::InsertInNewFile => "insertInNewFile",
            Self::CopyManual => "copyManual",
            Self::CopyButton => "copyButton",
            Self::Accept => "accept",
        }
    }
}

/// `IEditTelemetryCodeAcceptedData`.
#[derive(Clone, Debug)]
pub struct EditTelemetryCodeAcceptedData {
    pub base: EditTelemetryBaseData,
    /// Owning Agent Host session ID, omitted for suggestions without an Agent Host owner.
    pub agent_session_id: Option<String>,
    /// The agent implementation that produced the code block.
    pub provider: Option<String>,
    /// Canonical workbench chat ID, matching chat request telemetry.
    pub chat_session_id: Option<String>,
    pub acceptance_method: AcceptanceMethod,
}

/// `rejectionMethod`: `'reject'`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RejectionMethod {
    /// User explicitly rejected/undid the suggestion (when presentation is `highlightedEdit`) or pressed Escape (when
    /// feature is `inlineSuggestion`).
    Reject,
}

impl RejectionMethod {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Reject => "reject",
        }
    }
}

/// `IEditTelemetryCodeRejectedData`.
#[derive(Clone, Debug)]
pub struct EditTelemetryCodeRejectedData {
    pub base: EditTelemetryBaseData,
    pub agent_session_id: Option<String>,
    pub chat_session_id: Option<String>,
    pub rejection_method: RejectionMethod,
}
